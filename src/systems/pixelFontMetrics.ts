export const PIXEL_FONT_KEY = "ruby-rule-bitmap-font";
export const SMALL_PIXEL_FONT_KEY = "ruby-rule-bitmap-font-small";

/** Choose a native face at a whole-pixel scale; never discard glyph strokes. */
export function pixelFontMetrics(requested?: string | number) {
  const parsed = typeof requested === "string" ? Number.parseFloat(requested) : requested;
  const size = Math.max(6, typeof parsed === "number" && Number.isFinite(parsed) ? parsed : 8);
  const large = Math.floor(size / 8) * 8;
  const small = Math.floor(size / 6) * 6;
  const baseSize = large >= small ? 8 : 6;
  const fontSize = Math.max(6, large, small);
  return {
    key: baseSize === 8 ? PIXEL_FONT_KEY : SMALL_PIXEL_FONT_KEY,
    baseSize,
    fontSize,
    scale: fontSize / baseSize,
    advance: (baseSize === 8 ? 6 : 4) * (fontSize / baseSize)
  };
}

