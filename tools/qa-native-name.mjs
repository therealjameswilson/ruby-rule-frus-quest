import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const out = process.env.FRUS_QA_OUT ?? '/private/tmp/frus-native-name';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE });
try {
  const context = await browser.newContext({ viewport: { width: 375, height: 667 }, hasTouch: true, isMobile: true, deviceScaleFactor: 3 });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const tap = async (x, y) => {
    const b = await page.locator('canvas').first().boundingBox();
    await page.touchscreen.tap(b.x + x * b.width / 256, b.y + y * b.height / 240);
  };
  await page.goto('http://127.0.0.1:5195/?scene=CharacterCreateScene');
  await page.waitForFunction(() => window.game?.scene.isActive('CharacterCreateScene'));
  await page.waitForTimeout(800);
  await tap(128, 124);
  const input = page.getByRole('textbox', { name: 'Compiler name', exact: true });
  await input.waitFor({ state: 'visible' });
  assert.equal(await input.evaluate(e => e === document.activeElement), true);
  await page.keyboard.type('Ezrax', { delay: 100 });
  assert.equal(await input.inputValue(), 'Ezrax');
  await page.screenshot({ path: `${out}/editing.png` });
  await page.keyboard.press('Enter');
  await page.waitForTimeout(400);
  assert.equal(await page.locator('#compiler-name-dialog').count(), 0);
  assert.equal(await page.evaluate(() => window.game.scene.isActive('CharacterCreateScene')), true);
  const name = () => page.evaluate(() => window.game.scene.getScene('CharacterCreateScene').children.getByName('character-create-name').text);
  assert.equal(await name(), 'NAME: Ezrax');
  await tap(128, 124);
  await input.fill('discard');
  await page.getByRole('button', { name: 'Cancel', exact: true }).tap();
  assert.equal(await name(), 'NAME: Ezrax');
  await tap(128, 124);
  await input.fill('Ruby');
  await page.setViewportSize({ width: 667, height: 375 });
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${out}/landscape.png` });
  await page.setViewportSize({ width: 667, height: 160 });
  await page.waitForTimeout(250);
  const dialogBounds = await page.getByRole('dialog').boundingBox();
  assert(dialogBounds.y >= 0 && dialogBounds.y + dialogBounds.height <= 160, 'Name dialog fits a keyboard-sized visible viewport');
  await page.getByRole('button', { name: 'Done', exact: true }).tap();
  await page.setViewportSize({ width: 667, height: 375 });
  await page.waitForTimeout(300);
  assert.equal(await name(), 'NAME: Ruby');
  await tap(128, 188);
  await page.waitForFunction(() => window.game.scene.isActive('DanneIntroScene'));
  await page.waitForTimeout(350);
  await tap(213, 211);
  await page.waitForFunction(() => window.game.scene.isActive('OfficeScene'));
  await page.waitForTimeout(600);
  assert.equal(await page.locator('#compiler-name-dialog').count(), 0);
  await page.screenshot({ path: `${out}/office.png` });
  assert.deepEqual(errors, []);
  await writeFile(`${out}/result.json`, JSON.stringify({ nativeFocus: true, typedLetters: true, cancelPreserves: true, doneStaysInCreation: true, touchBegin: true, errors }, null, 2));
} finally { await browser.close(); }
